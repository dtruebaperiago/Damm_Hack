CREATE SCHEMA IF NOT EXISTS escolta;
REVOKE ALL ON SCHEMA escolta FROM PUBLIC;
SET search_path TO escolta, pg_catalog;
CREATE TABLE IF NOT EXISTS migrations(version INTEGER PRIMARY KEY);
CREATE TABLE IF NOT EXISTS historical_calibrations(id TEXT PRIMARY KEY, data JSONB NOT NULL);
CREATE TABLE IF NOT EXISTS waves(
  id TEXT PRIMARY KEY, parent_id TEXT UNIQUE REFERENCES waves(id), cycle TEXT NOT NULL,
  state TEXT NOT NULL DEFAULT 'draft', version INTEGER NOT NULL DEFAULT 1,
  config JSONB NOT NULL, survey JSONB NOT NULL, approved_hash TEXT,
  form_id TEXT UNIQUE, form_url TEXT, publish_title TEXT, source TEXT NOT NULL,
  snapshot JSONB, proposals JSONB, selected_action JSONB, created_at BIGINT NOT NULL
);
CREATE TABLE IF NOT EXISTS revisions(wave_id TEXT REFERENCES waves(id), version INTEGER, survey JSONB, config JSONB, approved_hash TEXT, PRIMARY KEY(wave_id,version));
CREATE TABLE IF NOT EXISTS credentials(cycle TEXT, participant TEXT, shift TEXT NOT NULL, PRIMARY KEY(cycle,participant));
CREATE TABLE IF NOT EXISTS deliveries(
  token_hash TEXT PRIMARY KEY, wave_id TEXT NOT NULL REFERENCES waves(id), participant TEXT NOT NULL,
  shift TEXT NOT NULL, created_at BIGINT NOT NULL, expires_at BIGINT NOT NULL, consumed INTEGER NOT NULL DEFAULT 0
);
CREATE TABLE IF NOT EXISTS accepted(
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, wave_id TEXT NOT NULL REFERENCES waves(id), form_id TEXT NOT NULL,
  external_id TEXT NOT NULL, source TEXT NOT NULL, answers JSONB NOT NULL, submitted_at BIGINT NOT NULL,
  UNIQUE(form_id,external_id)
);
CREATE TABLE IF NOT EXISTS response_links(
  wave_id TEXT REFERENCES waves(id), participant TEXT, response_id BIGINT UNIQUE REFERENCES accepted(id) ON DELETE CASCADE,
  shift TEXT NOT NULL, PRIMARY KEY(wave_id,participant)
);
CREATE TABLE IF NOT EXISTS sessions(token_hash TEXT PRIMARY KEY, expires_at BIGINT NOT NULL);
CREATE TABLE IF NOT EXISTS rate_limits(bucket TEXT PRIMARY KEY, count INTEGER NOT NULL, expires_at BIGINT NOT NULL);
CREATE INDEX IF NOT EXISTS accepted_wave_idx ON accepted(wave_id);
CREATE INDEX IF NOT EXISTS deliveries_expiry_idx ON deliveries(expires_at);
CREATE INDEX IF NOT EXISTS waves_cycle_idx ON waves(cycle);
ALTER TABLE migrations ENABLE ROW LEVEL SECURITY;
ALTER TABLE historical_calibrations ENABLE ROW LEVEL SECURITY;
ALTER TABLE waves ENABLE ROW LEVEL SECURITY;
ALTER TABLE revisions ENABLE ROW LEVEL SECURITY;
ALTER TABLE credentials ENABLE ROW LEVEL SECURITY;
ALTER TABLE deliveries ENABLE ROW LEVEL SECURITY;
ALTER TABLE accepted ENABLE ROW LEVEL SECURITY;
ALTER TABLE response_links ENABLE ROW LEVEL SECURITY;
ALTER TABLE sessions ENABLE ROW LEVEL SECURITY;
ALTER TABLE rate_limits ENABLE ROW LEVEL SECURITY;
